    private void initializeLogging() {
        String homePath = System.getProperty("user.home");

        String folderPath = homePath
                + File.separator + "Documents"
                + File.separator + "EduCore"
                + File.separator + "Logs";
        File newFolder = new File(folderPath);

        if (newFolder.exists()) {
            String fileName = "EduCore-Log-" + new SimpleDateFormat("yyyy-MM-dd_hh-mm-ss").format(new Date());
            if (handler == null) {
                try {
                    SignIn.handler = new FileHandler(folderPath + "/" + fileName + ".txt");
                    handler.setFormatter(new SimpleFormatter());
                    logger.addHandler(handler);
                    logger.setLevel(Level.ALL);
                    logger.info("Log file created successfully!");
                } catch (IOException e) {
                    logger.log(Level.WARNING, "Log file creation unsuccessful: " + e.getMessage(), e);
                    System.err.println("Failed to create log file: " + e.getMessage());
                } catch (SecurityException e) {
                    logger.log(Level.WARNING, "Security exception while creating log file: " + e.getMessage(), e);
                    System.err.println("Security exception creating log file: " + e.getMessage());
                }
            }
            return;
        }

        if (!newFolder.mkdirs()) {
            logger.log(Level.WARNING, "Failed to create log directory: " + folderPath);
            System.err.println("Failed to create log directory: " + folderPath);
        }
    }

