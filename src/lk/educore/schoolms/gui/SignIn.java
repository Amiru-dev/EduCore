    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = userNameField.getText().trim();
        String password = String.valueOf(jPasswordField1.getPassword());
        String role = (String) jComboBox1.getSelectedItem();

        try {
            DataValidator.isRequired(username, "Username");
            DataValidator.isRequired(password, "Password");

            ResultSet rs = MySQL.executeSearch("SELECT u.user_id, u.password, ut.type_name FROM user u "
                    + "JOIN user_type ut ON u.user_type_id = ut.user_type_id "
                    + "WHERE u.username = '" + username + "' AND ut.type_name = '" + role + "'");

            if (rs.next()) {
                String storedPassword = rs.getString("password");
                String actualRole = rs.getString("type_name");
                int userId = rs.getInt("user_id");

                if (PasswordUtil.checkPassword(password, storedPassword)) {
                    // Upgrade legacy plain-text password to BCrypt hash in DB
                    if (PasswordUtil.needsRehash(storedPassword)) {
                        try {
                            String newHashedPassword = PasswordUtil.hashPassword(password);
                            MySQL.executeIUD("UPDATE user SET password = '" + newHashedPassword + "' WHERE user_id = " + userId);
                            if ("Teacher".equals(actualRole)) {
                                MySQL.executeIUD("UPDATE teacher SET password = '" + newHashedPassword + "' WHERE user_id = " + userId);
                            }
                        } catch (Exception ex) {
                            logger.log(Level.WARNING, "Failed to upgrade password to BCrypt", ex);
                        }
                    }

                    // Populate UserSession
                    String teacherNIC = null;
                    int teacherId = -1;

                    if ("Teacher".equals(actualRole)) {
                        ResultSet trs = MySQL.executeSearch(
                            "SELECT NIC, teacher_id FROM teacher WHERE user_id = " + userId);
                        if (trs.next()) {
                            teacherNIC = trs.getString("NIC");
                            teacherId = trs.getInt("teacher_id");
                        }
                        trs.close();
                    }

                    lk.educore.schoolms.model.UserSession.init(
                        userId, username, actualRole, teacherNIC, teacherId);

                    // Route to appropriate dashboard based on role
                    dispose();
                    if ("Student".equals(actualRole)) {
                        new StudentDashboard(username).setVisible(true);
                    } else {
                        // Admin and Teacher go to main Dashboard
                        new Dashboard(username, actualRole).setVisible(true);
                    }
                    logger.log(Level.INFO, "Username: " + username + " signed in to the account");
                } else {
                    JOptionIcon.showErrorDialog(this, "Invalid password!");
                }
            } else {
                JOptionIcon.showErrorDialog(this, "User not found!");
            }

            rs.close();

        } catch (ValidationException e) {
            JOptionIcon.showWarningDialog(this, e.getUserFriendlyMessage());
        } catch (Exception e) {
            JOptionIcon.showErrorDialog(this, "Database error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

