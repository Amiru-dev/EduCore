    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {

            String vehicleType = jTextField1.getText();

            if (vehicleType.isEmpty()) {

                JOptionPane.showMessageDialog(this, "Please Enter the Vehicle Type to Add.", "Success", JOptionPane.OK_OPTION, JOptionIcon.WARNING.setICon());

            } else {
                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `vehicle_type` WHERE `vehicle_type`='" + vehicleType + "'");
                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "This Vehicle Type is Already Added.", "Success", JOptionPane.OK_OPTION, JOptionIcon.WARNING.setICon());
                    jTextField1.setText("");
                } else {
                    MySQL.executeIUD("INSERT INTO `vehicle_type`(`vehicle_type`) VALUES('" + vehicleType + "')");
                    JOptionPane.showMessageDialog(this, "Vehicle Type Added Successfully", "Success", JOptionPane.OK_OPTION, JOptionIcon.SUCCESS.setICon());
                    this.dispose();
                    transport.getLoadVehicleType();
                }

            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton1ActionPerformed


