    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String userName = userNameField.getText();
        String password = String.valueOf(jPasswordField1.getPassword());

        if (userName.isEmpty()) {
            ImageIcon icon = new ImageIcon("src/lk/corevision/fruitshop/resources/icons8-error-48.png");
            JOptionPane.showMessageDialog(this, "Please enter your username", "Warning", JOptionPane.WARNING_MESSAGE, icon);
        } else if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `employee` INNER JOIN `employee_type` ON "
                        + "`employee_type`.`employee_type_id`=`employee`.`employee_type_employee_type_id` "
                        + " WHERE employee.employee_status_id='1' AND `username`='" + userName + "' AND `password`='" + password + "'");
                if (resultSet.next()) {

                    Dashboard dashboard = new Dashboard(resultSet.getString("first_name"),
                            resultSet.getString("last_name"),
                            resultSet.getString("email"),
                            resultSet.getString("employee_type"));
                    logger.log(Level.INFO, "User: " + resultSet.getString("employee.NIC") + " is sign in to the account");
                    dashboard.setVisible(true);
                    this.dispose();

                    setEmployeeNIC(resultSet.getString("employee.NIC"));
                } else {
                    JOptionPane.showMessageDialog(this, "Invalid email or password", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            } catch (Exception e) {
                logger.log(Level.WARNING, "Signin Error!", e);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

