    private void jTable3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable3MouseClicked
        if (evt.getClickCount() == 2) {
            int row = jTable3.getSelectedRow();
            if (row != -1) {
                String inventoryId = String.valueOf(jTable3.getValueAt(row, 0));
                String fruitName = String.valueOf(jTable3.getValueAt(row, 2));

                HashMap Qualityhashmap = new HashMap();
                Qualityhashmap.put("id", inventoryId);
                Qualityhashmap.put("fName", fruitName);

                pq.setProductQuality(Qualityhashmap);
                if(this.stockDialog != null){
                      this.stockDialog.dispose();
                }
                
                
            } else {
                   JOptionPane.showMessageDialog(this, "Please enter a row", "Warning", JOptionPane.WARNING_MESSAGE);
            }

        }


    }//GEN-LAST:event_jTable3MouseClicked

    
    

