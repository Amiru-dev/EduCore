    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        
        if (Dashboard.getEmployeeTypeName().equals("Admin") || Dashboard.getEmployeeTypeName().equals("HR Manager")) {

            try {
                int row = jTable1.getSelectedRow();
                String id = String.valueOf(jTable1.getValueAt(row, 0));

                String eType = jLabel2.getText();

                String basicSalary = jFormattedTextField7.getText();
                String mA = jFormattedTextField8.getText();
                String tA = jFormattedTextField9.getText();
                String otR = jFormattedTextField10.getText();
                String epf = jFormattedTextField11.getText();


                if (DataValidator.isInvalidPrice(basicSalary)) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Price for Basic Salary");
                }else if (DataValidator.isInvalidPrice(mA)) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Price for Medical Allowance");
                } else if (DataValidator.isInvalidPrice(tA)) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Price for Travel Allowance");
                } else if (DataValidator.isInvalidPrice(otR)) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Price for OT Rate");
                } else if (epf.isEmpty()) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter EPF Value");
                }else {
                    ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `employee_salary_option` WHERE `employee_salary_option`.`id` = '"+id+"'");

                        MySQL.executeIUD("UPDATE `employee_salary_option` SET `basic_salary`='"+basicSalary+"',`medical_allowance`='"+mA+"',"
                                + "`travel_allowance`='"+tA+"',`ot_rate`='"+otR+"',epf='"+epf+"' WHERE `id`='"+id+"'");

                        loadSalaryOptions();
                        Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "Salary Option Updated Successfully");
                        resetBasicalaryOption();
                    
                }

            } catch (Exception e) {
                SignIn.getLoggerObject().log(Level.WARNING, "Employee Salary Option Update method Exception Found!", e);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Access blocked for role: " + Dashboard.getEmployeeTypeName(), "Access Denied", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        }
        
    }//GEN-LAST:event_jButton6ActionPerformed


