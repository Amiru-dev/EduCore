    private void loadSalaryOptions() {
        try {

            String query = "SELECT * FROM `employee_salary_option` INNER JOIN `employee_type` "
                    + "ON `employee_salary_option`.`id` = `employee_type`.`employee_salary_option_id`";

            ResultSet resultSet = MySQL.executeSearch(query);

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("employee_salary_option.id"));
                vector.add(resultSet.getString("employee_type.employee_type"));
                vector.add(resultSet.getString("employee_salary_option.basic_salary"));
                vector.add(resultSet.getString("employee_salary_option.medical_allowance"));
                vector.add(resultSet.getString("employee_salary_option.travel_allowance"));
                vector.add(resultSet.getString("employee_salary_option.ot_rate"));
                vector.add(resultSet.getString("employee_salary_option.epf"));
                
                model.addRow(vector);
            }

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "load Employee Salary Option method Exception Found!", e);
        }
    }

