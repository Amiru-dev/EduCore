    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        //add brand
        String brandname = jTextField6.getText();
        String description = jTextField5.getText();
        String supplier = String.valueOf(jComboBox1.getSelectedItem());

        if (brandname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter brand name", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (description.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a description", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (supplier.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a supplier", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else {
            try {

                String supplierId = supplierMap.get(supplier);

                if (supplierId == null) {
                    Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "Invalid supplier selected!");

                    return;
                }

                ResultSet resultSet = MySQL.executeSearch(
                        "SELECT `brand_id` FROM `brand` WHERE `brand_name` = '" + brandname + "'"
                );

                if (resultSet.next()) {
                    Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Brand already exists!");

                } else {

                    MySQL.executeIUD(
                            "INSERT INTO `brand` (`brand_name`, `description`) "
                            + "VALUES ('" + brandname + "', '" + description + "')"
                    );

                    ResultSet newBrandResult = MySQL.executeSearch(
                            "SELECT `brand_id` FROM `brand` WHERE `brand_name` = '" + brandname + "'"
                    );

                    if (newBrandResult.next()) {
                        String brandId = newBrandResult.getString("brand_id");

                        MySQL.executeIUD(
                                "INSERT INTO `supplier_has_brand` (`brand_brand_id`, `supplier_supplier_id`) "
                                + "VALUES ('" + brandId + "', '" + supplierId + "')"
                        );

                        Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "Brand added successfully!");

                        loadBrands();
                        reset();
                    } else {
                        Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "Failed to retreive Brand ID!");
                    }
                }
            } catch (Exception e) {
                SignIn.getLoggerObject().log(Level.WARNING,"add brand method exception found",e);
            }
        }
    }//GEN-LAST:event_jButton5ActionPerformed

