    private void supplierDropdown() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `supplier`");

            Vector<String> vector = new Vector<>();
            vector.add("Select");

            while (resultSet.next()) {
                vector.add(resultSet.getString("fname"));
                supplierMap.put(resultSet.getString("fname"), resultSet.getString("supplier_id"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"supplier dropdown method exception found",e);
        }
    }

    private void loadBrands() {
        try {

            ResultSet resultSet = MySQL.executeSearch(
                    "SELECT `brand`.`brand_name`, `brand`.`Description`, `supplier`.`fname` AS `supplier_name` "
                    + "FROM `brand` "
                    + "INNER JOIN `supplier_has_brand` ON `brand`.`brand_id` = `supplier_has_brand`.`brand_brand_id` "
                    + "INNER JOIN `supplier` ON `supplier_has_brand`.`supplier_supplier_id` = `supplier`.`supplier_id` ORDER BY `brand`.`brand_id` DESC ");

            DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
            model.setRowCount(0);

            int rowCount = 0;

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("brand_name"));
                vector.add(resultSet.getString("description"));
                vector.add(resultSet.getString("supplier_name"));

                model.addRow(vector);
                rowCount++;
            }

            if (rowCount == 0) {
                Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "No brands found!");

            }

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"load brands method exception found",e);
        }
    }

