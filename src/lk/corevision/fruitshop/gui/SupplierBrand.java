    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // update supplier brand
        String brandname = jTextField6.getText();
        String description = jTextField5.getText();
        String supplier = String.valueOf(jComboBox1.getSelectedItem());

        if (brandname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter brand name", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (description.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a description", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (jComboBox1.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select a supplier", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else {
            try {

                String supplierId = supplierMap.get(supplier);

                if (supplierId == null) {
                    Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "Invalid supplier selected!");

                    return;
                }

                String brandId = getBrandIdByName(brandname);

                if (brandId == null) {
                    Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "Brand Not found!");
                    return;
                }

                MySQL.executeIUD(
                        "UPDATE `brand` SET `brand_name` = '" + brandname + "', `description` = '" + description + "' "
                        + "WHERE `brand_id` = '" + brandId + "'");

                MySQL.executeIUD(
                        "UPDATE `supplier_has_brand` SET `supplier_supplier_id` = '" + supplierId + "' "
                        + "WHERE `brand_brand_id` = '" + brandId + "'");

                Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "Brand updated successfully!");

                loadBrands();
                jButton5.setEnabled(true);
                jTextField6.setEditable(true);

                reset();
            } catch (Exception e) {
                SignIn.getLoggerObject().log(Level.WARNING,"update supplier method exception found",e);
            }

        }


    }//GEN-LAST:event_jButton6ActionPerformed
    private String getBrandIdByName(String brandname) {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT `brand_id` FROM `brand` WHERE `brand_name` = '" + brandname + "'");
            if (resultSet.next()) {
                return resultSet.getString("brand_id");
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"get brand ID method exception found",e);
        }
        return null;
    }
