    private void loadIssueTable() {
        try {

            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `issue_type`");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("issue_type_id"));
                vector.add(resultSet.getString("issue_type"));

                model.addRow(vector);
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "production issue table loading Exception found!", e);
        }
    }

