    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String issue = jTextField2.getText();
            Pattern pattern = Pattern.compile("[a-zA-Z\\s]+");

            if (issue.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter an issue type", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else if (!pattern.matcher(issue).matches()) {
                JOptionPane.showMessageDialog(this, "Please enter only letters and spaces.", "Invalid Input", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else {

                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `issue_type` WHERE `issue_type` = '" + issue + "'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "This issue type is already added.", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else {
                    MySQL.executeIUD("INSERT INTO `issue_type`(`issue_type`) VALUES('" + issue + "')");

                    loadIssueTable();
                    reset();

                    JOptionPane.showMessageDialog(this, "New issue type added successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
                }
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "issue type Add Exception found!", e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            String issueId = id;
            String issue = jTextField2.getText();
            Pattern pattern = Pattern.compile("[a-zA-Z\\s]+");

            if (issue.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter an issue type", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else if (!pattern.matcher(issue).matches()) {
                JOptionPane.showMessageDialog(this, "Please enter only letters and spaces.", "Invalid Input", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else {

                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `issue_type` WHERE `issue_type` = '" + issue + "' AND `issue_type_id` = '" + issueId + "'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "This issue type is already added.", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else {
                    MySQL.executeIUD("UPDATE `issue_type` SET `issue_type_id` = '" + issueId + "', "
                            + "`issue_type` = '" + issue + "' "
                            + "WHERE `issue_type_id` = '" + issueId + "'");

                    loadIssueTable();
                    reset();

                    JOptionPane.showMessageDialog(this, "Issue type updated successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
                }
            }

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "issue type Update Exception found!", e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        JOptionPane optionPane = new JOptionPane(
                "Do you want to delete this issue type?",
                JOptionPane.QUESTION_MESSAGE,
                JOptionPane.YES_NO_OPTION
        );

        JDialog dialog = optionPane.createDialog(this, "Confirmation");
        dialog.setLocation(610, 330);
        dialog.setVisible(true);

        // Capture the result of the user's choice
        Object selectedValue = optionPane.getValue();

        if (selectedValue != null) {
            int result = (int) selectedValue;

            if (result == JOptionPane.YES_OPTION) {
                try {
                    String issueId = id;
                    MySQL.executeIUD("DELETE FROM `issue_type` WHERE `issue_type_id` = '" + issueId + "'");

                    loadIssueTable();
                    reset();

                    JOptionPane.showMessageDialog(this, "Issue type deleted successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
                } catch (Exception e) {
                    SignIn.getLoggerObject().log(Level.WARNING, "issue type Delete Exception found!", e);
                }

            } else if (result == JOptionPane.NO_OPTION) {
                reset();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row = jTable1.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row in table.", "Invalid Input", JOptionPane.ERROR_MESSAGE);
        } else {
            jButton1.setEnabled(false);
            jButton2.setEnabled(false);
            jButton3.setEnabled(false);

            id = String.valueOf(jTable1.getValueAt(row, 0));
            jTextField2.setText(String.valueOf(jTable1.getValueAt(row, 1)));

            if (evt.getClickCount() == 2) {

                String name = String.valueOf(jTable1.getValueAt(row, 1));
                if (product != null) {
                    product.setIssueType(name);
                    product.loadIssueTable();
                    this.dispose();
                }
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

