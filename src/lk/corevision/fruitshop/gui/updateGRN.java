    private void grnStatusUpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_grnStatusUpdateButtonActionPerformed
        try {
            String paidAmount = updateGRNPaymentField.getText();
            double amountPaid = 0;
            if (!paidAmount.isEmpty()) {
                amountPaid = Double.parseDouble(paidAmount);
            }

            double totalAmount = Double.parseDouble(updateGRNtotal.getText());

            int paymentStatusId;
            if (amountPaid >= totalAmount) {
                paymentStatusId = 1; // Fully Paid
            } else if (amountPaid > 0 && amountPaid < totalAmount) {
                paymentStatusId = 3; // Partially Paid
            } else {
                paymentStatusId = 2; // Not Paid
            }

            String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            MySQL.executeIUD("UPDATE `payment` SET `payment_method_id`='" + paymentMethodMap.get(GRNPaymentMethodComboBox.getSelectedItem()) + "',"
                    + "`payment_status_id`='" + paymentStatusId + "',`amount`='" + updateGRNPaymentField.getText() + "',`date`='" + date + "' "
                    + " WHERE `grn_grn_id`='" + updateGRNId.getText() + "'");
            MySQL.executeIUD("UPDATE `grn` SET `payment_status_id`='" + paymentStatusId + "',`paid_amount`='" + updateGRNPaymentField.getText() + "'"
                    + " WHERE `grn_id`='" + updateGRNId.getText() + "'");

            Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "GRN updated Successfuly!!");
            loadUpdateGRNitems();
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"update GRN status method exception found",e);
        }
    }//GEN-LAST:event_grnStatusUpdateButtonActionPerformed

    private void updateGRNPaymentFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_updateGRNPaymentFieldKeyReleased
        String payment = updateGRNPaymentField.getText();
        String total = updateGRNtotal.getText();

        if (payment.isEmpty()) {
            payment = "0.00";
        }
        if (DataValidator.isInvalidPrice(payment)) {
            JOptionPane.showMessageDialog(this, "Please Enter valid price", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            updateGRNPaymentField.setText("");
        } else {
            double balance = Double.parseDouble(total) - Double.parseDouble(payment);
            updateGRNBalance.setText(String.valueOf(balance));
            if (balance <= 0.00) {
                grnStatusUpdateButton.setEnabled(true);
            } else {
                grnStatusUpdateButton.setEnabled(false);
            }
        }
    }//GEN-LAST:event_updateGRNPaymentFieldKeyReleased

