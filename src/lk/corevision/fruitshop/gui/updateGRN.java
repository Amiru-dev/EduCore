    private void loadUpdateGRNitems() {
        try {
            ResultSet resultSet = MySQL.executeSearch(
                    "SELECT grn_items.`grn_items_id`, raw_material.`raw_material_id`, raw_material.`raw_material_name`, "
                    + "grn.`paid_amount` AS `paid_amount`, "
                    + "CONCAT(supplier.`fname`, ' ', supplier.`lname`) AS `supplier_name`, grn_items.`unit_price`, grn_items.`qty`, "
                    + "CONCAT(employee.`first_name`, ' ', employee.`last_name`) AS `employee_name`, "
                    + "grn.`date` AS `payment_date`, payment_status.`payment_status` AS `payment_status`, "
                    + "payment_status.`payment_status_id` AS `payment_status_id`, grn_status.`grn_status`, "
                    + "payment_method.`payment_method` AS `payment_method`, payment.`amount` AS `payment_amount`, payment.`date` AS `payment_date` "
                    + "FROM grn_items "
                    + "INNER JOIN grn ON grn_items.`grn_grn_id` = grn.`grn_id` "
                    + "INNER JOIN `employee` ON `employee`.`NIC` = `grn`.`employee_NIC` "
                    + "INNER JOIN raw_material ON grn_items.`raw_material_id` = raw_material.`raw_material_id` "
                    + "INNER JOIN supplier ON grn.`supplier_id` = supplier.`supplier_id` "
                    + "INNER JOIN payment_status ON grn.`payment_status_id` = payment_status.`payment_status_id` "
                    + "INNER JOIN grn_status ON grn_status.`grn_status_id` = grn.`grn_status_id` "
                    + "LEFT JOIN payment ON grn.`grn_id` = payment.`grn_grn_id` "
                    + "LEFT JOIN payment_method ON payment.`payment_method_id` = payment_method.`payment_method_id` "
                    + "WHERE grn.`grn_id` = '" + updateGRNId.getText() + "';"
            );

            DefaultTableModel model = (DefaultTableModel) viewGRNtable.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("raw_material_id"));
                vector.add(resultSet.getString("raw_material_name"));
                vector.add(resultSet.getString("supplier_name"));
                vector.add(resultSet.getString("qty"));
                vector.add(resultSet.getString("unit_price"));

                double itemTotal = Double.parseDouble(resultSet.getString("unit_price")) * Double.parseDouble(resultSet.getString("qty"));
                total += itemTotal;
                balance = total;
                vector.add(String.valueOf(itemTotal));
                vector.add(resultSet.getString("payment_date"));
                vector.add(resultSet.getString("payment_status"));
                model.addRow(vector);

                updateGRNEmployeeName.setText(resultSet.getString("employee_name"));
                updateGRNSupplierName.setText(resultSet.getString("supplier_name"));
                GRNstatusfield.setText(resultSet.getString("grn_status"));
                grnStatusComboBox.setSelectedItem(resultSet.getString("grn_status"));
                updateGRNPaymentStatus.setText(resultSet.getString("payment_status"));

                GRNDate.setText(resultSet.getString("payment_date"));

                if (resultSet.getString("payment_status_id").equals("1")) {
                    updateGRNPaymentField.setEditable(false);
                    GRNPaymentMethodComboBox.setEnabled(false);
                    updateGRNPaymentField.setText(String.valueOf(resultSet.getDouble("payment_amount")));
                    balance = total - resultSet.getDouble("payment_amount");
                    GRNPaymentMethodComboBox.setSelectedItem(resultSet.getString("payment_method"));
                    updateGRNPaymentDate.setText(resultSet.getString("payment_date"));
                }
                
                if (resultSet.getString("grn_status").equals("Complete")) {
                    jButton2.setEnabled(false);
                    grnStatusComboBox.setEnabled(false);
                    
                }

            }
            updateGRNtotal.setText(String.valueOf(total));
            updateGRNBalance.setText(String.valueOf(balance));
            total = 0;

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"load update GRN method exception found",e);
        }

    }

