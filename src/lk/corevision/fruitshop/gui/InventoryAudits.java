    private void inventoryAuditUpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_inventoryAuditUpdateButtonActionPerformed
        try {
            if (auditId != null) {
                String auditReson = inventoryAuditResonField.getText();
                String auditDescription = inventoryAuditDescriptionField.getText();
                if (auditReson.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please enter Audit Reson First", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else if (auditReson.length() < 5) {
                    JOptionPane.showMessageDialog(this, "Please enter Audit Reson for more than 5 characters", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else if (auditDescription.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please enter Audit Description", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else if (auditDescription.length() < 5) {
                    JOptionPane.showMessageDialog(this, "Please enter Audit Description for more than 5 characters", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else {
                    MySQL.executeIUD("UPDATE `inventory_audit` SET `audit_reason`='" + auditReson + "',`audit_description`='" + auditDescription + "' "
                            + "WHERE `inventory_audit_id`='" + auditId + "'");
                    System.out.println(auditId);
                    auditId = null;
                    reset();
                }
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "inventory audit Update Exception found!", e);
        }
    }//GEN-LAST:event_inventoryAuditUpdateButtonActionPerformed

    private void inventoryAuditAddButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_inventoryAuditAddButtonActionPerformed
        try {
            String auditReson = inventoryAuditResonField.getText();
            String auditDescription = inventoryAuditDescriptionField.getText();
            String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            if (auditReson.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter Audit Reson First", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
//            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter Audit Reson First");
            } else if (auditReson.length() < 5) {
                JOptionPane.showMessageDialog(this, "Please enter Audit Reson for more than 5 characters", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else if (auditDescription.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter Audit Description", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
//            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter Audit Description");
            } else if (auditDescription.length() < 5) {
                JOptionPane.showMessageDialog(this, "Please enter Audit Description for more than 5 characters", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else {
                MySQL.executeIUD("INSERT INTO `inventory_audit`(`odit_date`,`audit_reason`,`audit_description`,`inventory_inventory_id`,`employee_NIC`) "
                        + "VALUES ('" + date + "','" + auditReson + "','" + auditDescription + "',"
                        + "'" + inventoryAuditInventoryIdField.getText() + "','" + SignIn.getEmployeeNIC() + "')");
                reset();
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "inventory audit Add Exception found!", e);
        }
    }//GEN-LAST:event_inventoryAuditAddButtonActionPerformed

