    private void inventoryAuditDeleteMenuItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_inventoryAuditDeleteMenuItemActionPerformed
        try {
            int row = jTable2.getSelectedRow();
            if (row != -1) {
                String auditId = String.valueOf(jTable2.getValueAt(row, 0));
                int showConfirmDialog = JOptionPane.showConfirmDialog(this, "are you sure you want to delete Audit id:" + auditId, "Warrning", JOptionPane.YES_NO_OPTION);
                if (JOptionPane.YES_OPTION == showConfirmDialog) {
                    MySQL.executeIUD("DELETE FROM `inventory_audit` WHERE `inventory_audit_id`='" + auditId + "' ");
                    JOptionPane.showMessageDialog(this, "success Fully Deleted Audit :" + auditId, "Warning", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.INFO.setICon());
//                    Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "success Fully Deleted Campaign :" + auditId);
                    reset();
                } else {
                    JOptionPane.showMessageDialog(this, "Delete unsuccess Audit :" + auditId, "Warning", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
//                    Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT, "Delete unsuccess campaign :" + auditId);

                }
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "inventory audit Delete Exception found!", e);
        }
    }//GEN-LAST:event_inventoryAuditDeleteMenuItemActionPerformed


