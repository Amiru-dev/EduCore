    private void loadAudits() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT `inventory_id`,`first_name`,`last_name`,`inventory_audit_id`,"
                    + "`fruit_name`,`odit_date`,`audit_reason`,`audit_description`"
                    + " FROM `inventory` INNER JOIN `inventory_audit` ON "
                    + "`inventory`.`inventory_id`=`inventory_audit`.`inventory_inventory_id` INNER JOIN `employee` ON "
                    + "`employee`.`NIC`=`inventory_audit`.`employee_NIC` INNER JOIN `plantation`  ON"
                    + "`plantation`.`plantation_id` = `inventory`.`plantation_id` "
                    + "INNER JOIN `fruit` ON `plantation`.`fruit_fruit_id` = `fruit`.`fruit_id`"
                    + " WHERE `inventory_inventory_id`='" + inventoryAuditInventoryIdField.getText() + "' ");

            DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("inventory_audit_id"));
                vector.add(resultSet.getString("inventory_id"));
                vector.add(resultSet.getString("fruit_name"));
                vector.add(resultSet.getString("odit_date"));
                vector.add(resultSet.getString("audit_reason"));
                vector.add(resultSet.getString("audit_description"));
                vector.add(resultSet.getString("first_name") + " " + resultSet.getString("last_name"));
                model.addRow(vector);
            }

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "loadAudits method Exception found!", e);
        }
    }

