    private void loadCustomerStatus() {

        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `customer_status`");

            Vector<String> vector = new Vector<>();
            vector.add("Select");
            while (resultSet.next()) {

                vector.add(resultSet.getString("customer_status"));
                customerStatMap.put(resultSet.getString("customer_status"), resultSet.getString("customer_status_id"));

            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            DefaultComboBoxModel model2 = new DefaultComboBoxModel(vector);

            jComboBox1.setModel(model);
            jComboBox2.setModel(model2);

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "Customer Status Loading Exception Found", e);

        }

    }

