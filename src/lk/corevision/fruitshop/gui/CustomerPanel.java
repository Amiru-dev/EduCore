    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String customerNic = jTextField1.getText();
        String customerFname = jTextField2.getText();
        String customerLname = jTextField3.getText();
        String customerEmail = jTextField4.getText();
        String customerMobile = jTextField7.getText();
        String customerStat = String.valueOf(jComboBox1.getSelectedItem());

        if (customerNic.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Your NIC Number");

        } else if (DataValidator.isInvalidNIC(customerNic)) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid NIC Number");

        } else if (customerFname.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Your First Name");

        } else if (DataValidator.isInvalidLetter(customerFname)) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid First Name");

        } else if (customerFname.length() > 45) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid First Name");

        } else if (customerLname.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Your Last Name");

        } else if (DataValidator.isInvalidLetter(customerLname)) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Last Name");

        } else if (customerLname.length() > 45) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Last Name");

        } else if (customerEmail.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Your Email Address");

        } else if (DataValidator.isInvalidEmail(customerEmail)) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Email Address");

        } else if (customerMobile.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Your Mobile Number");

        } else if (DataValidator.isInvalidMobile(customerMobile)) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Enter Valid Mobile Number");

        } else if (customerStat.equals("Select")) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please Select the Customer Status");

        } else {

            try {
                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `customer` WHERE `email`='" + customerEmail + "'");
                boolean canUpdate = false;

                if (resultSet.next()) {

                    if (customerNic.equals(resultSet.getString("customer_nic"))) {
                        canUpdate = true;
                    } else {
                        Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "This email is already registered.");

                    }

                } else {
                    canUpdate = true;
                }

                if (canUpdate) {

                    MySQL.executeIUD("UPDATE `customer` SET `first_name`='" + customerFname + "',`last_name`='" + customerLname + "',`email`='" + customerEmail + "',`mobile`='" + customerMobile + "',`customer_status_id`='" + customerStatMap.get(customerStat) + "' WHERE `customer_nic`='" + customerNic + "'");
                    Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "This Customer is Successfully Updated.");

                    loadCustomer();
                    clearFields();

                }

            } catch (Exception ex) {
                SignIn.getLoggerObject().log(Level.WARNING, "Customer Update Exception Found", ex);

            }

        }

    }//GEN-LAST:event_jButton2ActionPerformed

