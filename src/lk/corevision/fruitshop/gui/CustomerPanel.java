    private void loadCustomer() {

        try {

            String query = "SELECT * FROM `customer` INNER JOIN `customer_status` ON `customer`.`customer_status_id` = `customer_status`.`customer_status_id` ";

            boolean hasWhereClause = false;

            if (!jTextField5.getText().isEmpty()) {
                query += "WHERE `customer`.`customer_nic` LIKE '%" + jTextField5.getText() + "%' ";
                hasWhereClause = true;
            }

            if (!jComboBox2.getSelectedItem().equals("Select")) {
                if (hasWhereClause) {
                    query += "AND ";
                } else {
                    query += "WHERE ";
                }
                query += "`customer`.`customer_status_id`='" + customerStatMap.get(jComboBox2.getSelectedItem()) + "' ";
            }
            ResultSet resultSet = MySQL.executeSearch(query);

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("customer_nic"));
                vector.add(resultSet.getString("first_name"));
                vector.add(resultSet.getString("last_name"));
                vector.add(resultSet.getString("email"));
                vector.add(resultSet.getString("mobile"));
                vector.add(resultSet.getString("customer_status.customer_status"));
                vector.add(resultSet.getString("employee_NIC"));

                model.addRow(vector);
            }

            jTable1.setModel(model);

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "Customer Loading Exception Found", e);
        }

    }

