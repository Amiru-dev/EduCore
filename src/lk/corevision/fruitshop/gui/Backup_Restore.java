    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            MySQL db = createConnection();

            if (db == null) {
                JOptionPane.showMessageDialog(this, "Database connection failed. Please check configuration.", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
                return;
            }

            Date date = new Date();
            String date1 = new SimpleDateFormat("yyyy-MM-dd-HH-mm-ss").format(date);
            String path = db.path + "/" + date1 + ".sql";

            ProcessBuilder pb = new ProcessBuilder(
                    db.dump,
                    "-u" + db.un,
                    "-p" + db.pw,
                    "--add-drop-database",
                    "-B", db.dbname,
                    "-r", path
            );
            pb.redirectErrorStream(true);
            Process p1 = pb.start();

            String output = new String(p1.getInputStream().readAllBytes());
            int exitCode = p1.waitFor();

            if (exitCode == 0) {
                JOptionPane.showMessageDialog(this, "Backup Saved: " + path, "Info", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.SUCCESS.setICon());
            } else {
                JOptionPane.showMessageDialog(this, "Backup failed!\n" + output, "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private MySQL createConnection() {
        try {
            Key secretKey = new SecretKeySpec(KEY, ALGORITHM);
            Cipher cipher = Cipher.getInstance(ALGORITHM);
            cipher.init(Cipher.DECRYPT_MODE, secretKey);

            FileInputStream fileInputStream = new FileInputStream("dbinfor.ser");
            CipherInputStream cipherInputStream = new CipherInputStream(fileInputStream, cipher);
            ObjectInputStream objectInputStream = new ObjectInputStream(cipherInputStream);
            MySQL db = (MySQL) objectInputStream.readObject();
            objectInputStream.close();
            return db;

        } catch (Exception ex) {
            Logger.getLogger(Backup_Restore.class.getName()).log(Level.SEVERE, null, ex);
            return null;
        }
    }

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            MySQL db = createConnection();

            if (db == null) {
                JOptionPane.showMessageDialog(this, "Database connection failed. Please check configuration.", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
                return;
            }

            String path = jTextField1.getText().trim();

            if (path.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please set a valid restore path", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                return;
            }

            File selectedFile = new File(path);

            if (!selectedFile.exists() || !selectedFile.isFile() || !selectedFile.getName().toLowerCase().endsWith(".sql")) {
                JOptionPane.showMessageDialog(this, "Please select a valid .sql file", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                return;
            }

            String mysqlExe = db.dump.replace("mysqldump", "mysql");

            ProcessBuilder pb = new ProcessBuilder(
                    mysqlExe,
                    "-u" + db.un,
                    "-p" + db.pw,
                    db.dbname
            );
            pb.redirectInput(selectedFile);
            pb.redirectErrorStream(true);
            Process p1 = pb.start();

            String output = new String(p1.getInputStream().readAllBytes());
            int exitCode = p1.waitFor();

            if (exitCode == 0) {
                JOptionPane.showMessageDialog(this, "Restore successful", "Info", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.SUCCESS.setICon());
            } else {
                JOptionPane.showMessageDialog(this, "Restore failed! Please try again later.\n" + output, "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

