    private void loadCities() {
        
        try {
            
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `city`");
            
            Vector<String> vector = new Vector<>();
            vector.add("Select");
            
            while (resultSet.next()) {
                vector.add(resultSet.getString("city_name"));
                cityMap.put(resultSet.getString("city_name"), resultSet.getString("city_id"));
            }
            
            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);
            
        } catch (Exception e) {
           SignIn.getLoggerObject().log(Level.WARNING,"load cities method exception found",e);        }
    }
    
    private void loadAddress() {
        try {
            
            String query = "SELECT `supplier_address_id`, `line1`, `line2`, `city_name` FROM "
                    + "`supplier_address` INNER JOIN `city` ON "
                    + "`supplier_address`.`city_city_id` = `city`.`city_id` WHERE `supplier_id` ='" + this.supplierId + "'";
            
            ResultSet resultSet = MySQL.executeSearch(query);
            
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);            
            
            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("supplier_address_id"));
                vector.add(resultSet.getString("line1"));
                vector.add(resultSet.getString("line2"));
                vector.add(resultSet.getString("city_name"));
                model.addRow(vector);
                
            }
            
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING,"load addresses method exception found",e);
            }
    }

