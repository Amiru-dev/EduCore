    private void removeAddressMenuItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeAddressMenuItemActionPerformed
        // Remove address
        int row = jTable1.getSelectedRow();
        if (JOptionPane.showConfirmDialog(this, "Are you sure you want to delete the address?", "Confirm Deletion", JOptionPane.OK_CANCEL_OPTION, JOptionPane.WARNING_MESSAGE) == JOptionPane.OK_OPTION) {
            try {
                String id = String.valueOf(jTable1.getValueAt(row, 0));
                MySQL.executeIUD("DELETE FROM `supplier_address` WHERE `supplier_address_id` ='" + id + "'");
                
                loadAddress();
                reset();
                Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT, "Address deleted successfully!");
                
            } catch (Exception e) {
                SignIn.getLoggerObject().log(Level.WARNING,"remove address method exception found",e);
            }
        }

    }//GEN-LAST:event_removeAddressMenuItemActionPerformed

