    private void marketingUpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_marketingUpdateButtonActionPerformed
        String campaignName = campaignNameField.getText();
        Date fromDate = dateFromChooser.getDate();
        Date toDate = dateToChooser.getDate();
        String campaignBudget = campaignBudgetField.getText();
        String targetAudience = targetAudienceField.getText();
        SimpleDateFormat simpleDateFormat = new SimpleDateFormat("yyyy-MM-dd");

        try {
            if (campaignName.isEmpty()) {
//            JOptionPane.showMessageDialog(this, "Please enter Campaign Name", "Warning", JOptionPane.WARNING_MESSAGE);
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter Campaign Name");
            } else if (fromDate == null) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please select From Date");
            } else if (toDate == null) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please select To Date");
            } else if (targetAudience.isEmpty()) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter campaign target audience or description");
            } else if (campaignBudget.isEmpty()) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter campaign Budget");
            } else if (Double.parseDouble(campaignBudget) <= 0) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT, "Please enter valid campaign Budget");
            } else {
                MySQL.executeIUD("UPDATE `campaigns` SET `campaign_name`='" + campaignName + "',`start_date`='" + simpleDateFormat.format(fromDate) + "',"
                        + "`end_date`='" + simpleDateFormat.format(toDate) + "' "
                        + ",`budget`='" + campaignBudget + "' ,`target_audience`='" + targetAudience + "',"
                        + "`campaign_status_id`='" + campaignStatusMap.get(campaignStatusComboBox.getSelectedItem()) + "' ,`employee_NIC`='" + SignIn.getEmployeeNIC() + "'   "
                        + " WHERE `campaign_id`='" + campaignIdField.getText() + "' ");

                reset();
            }
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "Marketing row Update Exception Found!!", e);
        }
    }//GEN-LAST:event_marketingUpdateButtonActionPerformed

