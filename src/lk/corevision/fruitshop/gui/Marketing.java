    private void loadCampaignStatus() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `campaign_status`");

            Vector<String> vector = new Vector<>();

            while (resultSet.next()) {
                vector.add(resultSet.getString("campaign_status"));
                campaignStatusMap.put(resultSet.getString("campaign_status"), resultSet.getString("campaign_status_id"));

            }
            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            campaignStatusComboBox.setModel(model);
        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "loadCampaignStatus method Exception Found!!", e);
        }
    }

    private void loaCampaigns() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `campaigns` INNER JOIN `campaign_status` ON "
                    + "`campaign_status`.`campaign_status_id`=`campaigns`.`campaign_status_id` INNER JOIN `employee` ON"
                    + "`employee`.`NIC`=`campaigns`.`employee_NIC`");

            DefaultTableModel model = (DefaultTableModel) CampaignTable.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("campaign_id"));
                vector.add(resultSet.getString("campaign_name"));
                vector.add(resultSet.getString("start_date"));
                vector.add(resultSet.getString("end_date"));
                vector.add(resultSet.getString("target_audience"));
                vector.add(resultSet.getString("campaign_status"));
                vector.add(resultSet.getString("budget"));
                vector.add(resultSet.getString("first_name") + " " + resultSet.getString("last_name"));
                vector.add(resultSet.getString("added_date"));
                model.addRow(vector);
            }

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "loaCampaigns method Exception Found!!", e);
        }
    }

