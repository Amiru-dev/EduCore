    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        MySQL db = new MySQL();

        String ip = setupConnectionIpAddressField.getText();
        String port = setupConnectionPort.getText();
        String dbname = setupConnectionDbName.getText();
        String userName = setupConnectionUsername.getText();
        String password = String.valueOf(setupConnectionPassword.getPassword());
        String dumpFile = setupConnectionDumpFileField.getText();
        String path = setupConnectionBackupPath.getText();

        if (ip.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Ip address", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (port.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter port number", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (dbname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Database Name", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (userName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter user name of database", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter password", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (dumpFile.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter the correct mysql dumpfile", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (path.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter the backup file saving path", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else {
            db.ip = ip.trim();
            db.port = port.trim();
            db.dbname = dbname.trim();
            db.un = userName.trim();
            db.pw = String.valueOf(password).trim();
            db.dump = dumpFile.trim();
            db.path = path.trim();

            try {
                Key secretKey = new SecretKeySpec(KEY, ALGORITHM);
                Cipher cipher = Cipher.getInstance(ALGORITHM);
                cipher.init(Cipher.ENCRYPT_MODE, secretKey);

                FileOutputStream fileOutputStream = new FileOutputStream("dbinfor.ser");
                CipherOutputStream cipherOutputStream = new CipherOutputStream(fileOutputStream, cipher);
                ObjectOutputStream objectOutputStream = new ObjectOutputStream(cipherOutputStream);
                objectOutputStream.writeObject(db);
                objectOutputStream.close();
                db.createConnection();
                JOptionPane.showMessageDialog(this, "Connection successful", "Info", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.SUCCESS.setICon());
                this.dispose();
                new SignIn().setVisible(true);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Connection unsuccessful", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

