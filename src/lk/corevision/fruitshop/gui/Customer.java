    private void dashBoardDataSet() {

        int activeCustomers = 0;
        int inactiveCustomers = 0;
        int locationCount = 0;

        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `customer`");
            while (resultSet.next()) {

                if (resultSet.getInt("customer_status_id") == 1) {
                    activeCustomers++;
                } else if (resultSet.getInt("customer_status_id") == 2) {
                    inactiveCustomers++;
                }

            }

            jLabel4.setText(String.valueOf(activeCustomers));
            jLabel5.setText(String.valueOf(inactiveCustomers));

            ResultSet resultSet2 = MySQL.executeSearch("SELECT * FROM `customer_address`");

            while (resultSet2.next()) {
                locationCount++;
            }

            jLabel6.setText(String.valueOf(locationCount));

        } catch (Exception e) {
            SignIn.getLoggerObject().log(Level.WARNING, "Customer Dashboard Active Inactive Counting Exception Found", e);

        }

    }

